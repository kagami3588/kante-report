def H1(t): story.append(Spacer(1, 2)); P(t, h1)
def H2(t): P(t, h2)
def SP(h=4): story.append(Spacer(1, h))
def BL(items):
    for i in items: P("・" + i)
def NOTE(t): P(t, note)

def TBL(rows, widths, header=True):
    data = []
    for r, row in enumerate(rows):
        st = cellh if (header and r == 0) else cell
        data.append([Paragraph(str(c), st) for c in row])
    t = Table(data, colWidths=[w * mm for w in widths], repeatRows=1 if header else 0)
    style = [("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
             ("VALIGN", (0, 0), (-1, -1), "TOP"),
             ("LEFTPADDING", (0, 0), (-1, -1), 3), ("RIGHTPADDING", (0, 0), (-1, -1), 3)]
    if header:
        style += [("BACKGROUND", (0, 0), (-1, 0), NAVY)]
        style += [("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT])]
    t.setStyle(TableStyle(style))
    story.append(t); SP(6)

